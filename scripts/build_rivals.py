"""Builds src/lib/rivalsData.ts: every grandmaster, as Trayner's rival names ("GM A. Giri").

Sources (CSV, downloaded by hand):
  1. Wikipedia's "List of chess grandmasters" (all GMs ever, deceased included), as packaged in
     https://github.com/aswanijehangeer/ChessGMsdata  (data-raw/chess-grandmasters.csv)
  2. FIDE's rating list, for grandmasters titled since:
     https://github.com/rfordatascience/tidytuesday  (data/2025/2025-09-23/fide_ratings_september.csv)

Players born in 2008 or later are left out (no minors). Run:
  python3 scripts/build_rivals.py chess-grandmasters.csv fide_ratings_september.csv
"""
import csv
import json
import re
import sys
from pathlib import Path

LAST_BIRTH_YEAR = 2007
# Legends from before the GM title existed: shown without a title.
LEGENDS = ["J.R. Capablanca", "A. Alekhine", "E. Lasker", "P. Morphy", "A. Nimzowitsch", "W. Steinitz"]


def year(s: str) -> int | None:
    m = re.match(r"\s*(\d{4})", s or "")
    return int(m.group(1)) if m else None


def initials(given: str) -> str:
    parts = [p for p in re.split(r"[\s\-]+", given.strip()) if p and p[0].isalpha()]
    return "".join(p[0].upper() + "." for p in parts)


def short(name: str) -> str:
    name = re.sub(r"\s+", " ", name.replace(" ", " ")).strip().strip('"')
    if "," not in name:
        return name  # e.g. "Gukesh D", as FIDE writes it
    surname, given = (x.strip() for x in name.split(",", 1))
    ini = initials(given)
    return f"{ini} {surname}" if ini else surname


def full(name: str) -> str:
    name = re.sub(r"\s+", " ", name.replace(" ", " ")).strip().strip('"')
    if "," not in name:
        return name
    surname, given = (x.strip() for x in name.split(",", 1))
    return f"{given} {surname}".strip()


def main(wiki_csv: str, fide_csv: str) -> None:
    players: dict[str, str] = {}  # key (FIDE id or name) -> name as "Surname, Given"
    with open(wiki_csv, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            y = year(r.get("date_of_birth", ""))
            if y is not None and y > LAST_BIRTH_YEAR:
                continue
            fid = (r.get("fide_id") or "").strip()
            key = fid if fid and fid != "NA" else "n:" + r["name"].strip()
            players[key] = r["name"]
    with open(fide_csv, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            if r.get("title") != "GM":
                continue
            y = year(r.get("bday", ""))
            if y is None or y > LAST_BIRTH_YEAR:
                continue
            players.setdefault(r["id"].strip(), r["name"])  # Wikipedia's spelling wins when both have it

    names = list(players.values())
    shown = [short(n) for n in names]
    counts: dict[str, int] = {}
    for s in shown:
        counts[s] = counts.get(s, 0) + 1
    # two players with the same initial and surname: use the full given name for both
    out = sorted({"GM " + (full(n) if counts[s] > 1 else s) for n, s in zip(names, shown)} | set(LEGENDS))

    body = ",\n".join("  " + json.dumps(n, ensure_ascii=False) for n in out)
    ts = (
        "// Generated by scripts/build_rivals.py — do not edit by hand.\n"
        f"// {len(out)} names: every grandmaster (Wikipedia + FIDE), no one born after {LAST_BIRTH_YEAR}.\n"
        "export const RIVALS: string[] = [\n" + body + ",\n];\n"
    )
    Path(__file__).resolve().parent.parent.joinpath("src/lib/rivalsData.ts").write_text(ts, encoding="utf-8")
    print(f"{len(out)} rivals; longest: {max(out, key=len)!r} ({max(map(len, out))} chars)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
