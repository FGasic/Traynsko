writeFileSync('src/generated/pieces.ts', '// generated by build.mjs from assets/pieces-centered.css\nexport const PIECE_SVG: Record<string, string> = ' + JSON.stringify(pieces) + ';\n');
if (Object.keys(pieces).length !== 6) throw new Error('piece extraction failed');
