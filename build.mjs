import { build, transform } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, unlinkSync } from 'fs';

const out = 'dist';
mkdirSync(out, { recursive: true });

// Piece artwork for emblems and promotion buttons (white set used as a luminance mask).
const pieceCss = readFileSync('assets/pieces-centered.css', 'utf8');
const pieces = {};
for (const m of pieceCss.matchAll(/\.cg-wrap piece\.(\w+)\.white\s*\{\s*background-image:\s*url\('data:image\/svg\+xml;base64,([^']+)'\)/g)) pieces[m[1]] = m[2];
mkdirSync('src/generated', { recursive: true });
writeFileSync('src/generated/pieces.ts', '// generated by build.mjs from assets/pieces-centered.css\nexport const PIECE_SVG: Record<string, string> = ' + JSON.stringify(pieces) + ';\n');
if (Object.keys(pieces).length !== 6) throw new Error('piece extraction failed');
const js = await build({
  entryPoints: ['src/main.tsx'], bundle: true, write: false, minify: true, format: 'iife', target: 'es2020',
  jsx: 'automatic', jsxImportSource: 'preact', legalComments: 'none',
});
const code = js.outputFiles[0].text;
const cssSrc = ['node_modules/chessground/assets/chessground.base.css', 'assets/pieces-centered.css', 'src/styles.css']
  .map((f) => readFileSync(f, 'utf8')).join('\n');
const css = (await transform(cssSrc, { loader: 'css', minify: true })).code;
const preload = ['cinzel-latin-800-normal.woff2', 'alegreya-sans-latin-400-normal.woff2'].map((f) => `<link rel="preload" href="/fonts/${f}" as="font" type="font/woff2" crossorigin>`).join('\n');
// Self-hosted fonts (no third-party requests): Cinzel for display, Alegreya Sans for text.
mkdirSync(`${out}/fonts`, { recursive: true });
const FONT_FILES = [['cinzel', 'Cinzel', [500, 700, 800, 900]], ['alegreya-sans', 'Alegreya Sans', [400, 500, 700, 800]]];
let fontCss = '';
for (const [pkg, family, weights] of FONT_FILES) for (const w of weights) {
  const f = `${pkg}-latin-${w}-normal.woff2`;
  copyFileSync(`node_modules/@fontsource/${pkg}/files/${f}`, `${out}/fonts/${f}`);
  fontCss += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(/fonts/${f}) format("woff2")}`;
}
const v = Date.now().toString(36);
writeFileSync(`${out}/app.${v}.js`, code);
writeFileSync(`${out}/app.${v}.css`, fontCss + css);
// remove previous hashed bundles
for (const f of readdirSync(out)) if (/^app\.[a-z0-9]+\.(js|css)$/.test(f) && !f.includes(v)) unlinkSync(`${out}/${f}`);
const html = `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Traynsko</title>
<meta name="description" content="Entrena tu repertorio de aperturas y juega la posición contra bots.">
<meta name="theme-color" content="#04060b">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/icon-192.png">
<link rel="manifest" href="/manifest.webmanifest">
${preload}
<link rel="stylesheet" href="/app.${v}.css">
</head>
<body>
<div id="root"></div>
<script src="/app.${v}.js" defer></script>
</body>
</html>
`;
writeFileSync(`${out}/index.html`, html);
for (const f of ['icon.svg', 'icon-192.png', 'icon-512.png', 'manifest.webmanifest']) copyFileSync(`assets/${f}`, `${out}/${f}`);
for (const f of ['stockfish-19-lite-single.js', 'stockfish-19-lite-single.wasm', 'stockfish-19-asm.js']) copyFileSync(`node_modules/stockfish/bin/${f}`, `${out}/${f}`);
console.log('built', `app.${v}.js`, (code.length / 1024).toFixed(0) + ' KB');

// ---------- Vercel Build Output API: static files + one Node function for /api/* ----------
import { rmSync, cpSync } from 'fs';
const vo = '.vercel/output';
rmSync(vo, { recursive: true, force: true });
mkdirSync(`${vo}/functions/api.func`, { recursive: true });
cpSync(out, `${vo}/static`, { recursive: true });
await build({
  entryPoints: ['server/vercel.ts'], bundle: true, platform: 'node', format: 'cjs', target: 'node20',
  outfile: `${vo}/functions/api.func/index.js`, minify: false, legalComments: 'none', logLevel: 'warning',
});
writeFileSync(`${vo}/functions/api.func/.vc-config.json`, JSON.stringify({ runtime: 'nodejs22.x', handler: 'index.js', launcherType: 'Nodejs', shouldAddHelpers: true, maxDuration: 30 }, null, 2));
writeFileSync(`${vo}/config.json`, JSON.stringify({
  version: 3,
  routes: [
    { src: '/(stockfish-.*|fonts/.*|app\\..*)', headers: { 'Cache-Control': 'public, max-age=31536000, immutable' }, continue: true },
    { src: '/(.*)', headers: { 'X-Content-Type-Options': 'nosniff', 'Referrer-Policy': 'strict-origin-when-cross-origin' }, continue: true },
    { src: '/api/(.*)', dest: '/api?__path=$1' },
    { handle: 'filesystem' },
  ],
}, null, 2));
console.log('vercel output ready');
